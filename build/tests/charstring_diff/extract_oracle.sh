#!/usr/bin/env bash
#
# Generate the C-vs-Zig differential oracle (Annex A5).
#
# Extracts the PINNED upstream C bodies of a set of self-contained pure functions
# from src/c47/charString.c, renamed with an `oracle_` prefix (definitions AND
# cross-calls), so the differential harness can compile the upstream C and the
# Zig port into one binary and byte-compare them over enumerated inputs. Keeping
# the oracle sourced from the real pinned file (not a hand copy) means an M10 pin
# bump that changes any of these functions changes the oracle too -- exactly the
# divergence the differential then catches against the (re-ported) Zig owner.
#
# stringByteLength is a strlen macro (charString.h), supplied below, so the whole
# glyph cluster is self-contained.
#
# Run from anywhere; rewrites charstring_diff_oracle.c next to this script. The
# harness fails if the committed oracle is stale, so CI / the M10 cycle re-runs
# this and commits the result.
set -euo pipefail

# Functions to lift (the closure must be complete: every cross-call target listed).
FUNCS=(stringGlyphLength stringNextGlyphNoEndCheck_JM stringNextGlyph stringPrevGlyph stringLastGlyph stringToFileNameChars)

repo_root="$(cd "$(dirname "$0")/../../.." && pwd)"
src="$repo_root/src/c47/charString.c"
out="$(dirname "$0")/charstring_diff_oracle.c"

# Brace-match one function out of the pinned source (K&R: close brace in col 0).
extract() {
  awk -v f="$1" '
    $0 ~ "^(int16_t|int32_t|uint32_t|int|void) "f"\\(" { c=1 }
    c { print }
    c && /^\}/ { exit }
  ' "$src"
}

# Build a sed program that renames every listed function name -> oracle_name
# (matches both `<type> name(` definitions and `name(` calls).
sed_prog=""
for f in "${FUNCS[@]}"; do
  sed_prog+="s/\\b${f}(/oracle_${f}(/g;"
done

{
  echo "// GENERATED by build/tests/charstring_diff/extract_oracle.sh -- DO NOT EDIT."
  echo "// Pinned upstream C of the charString glyph cluster (src/c47/charString.c),"
  echo "// renamed oracle_* so it links beside the Zig owner exports for A5 diffing."
  echo "#include <stdint.h>"
  echo "#include <string.h>"
  echo "#define stringByteLength(str) ((int32_t)strlen(str)) // charString.h"
  echo
  echo "// forward declarations (the cluster is mutually recursive)"
  for f in "${FUNCS[@]}"; do
    extract "$f" | head -1 | sed "${sed_prog}s/ {.*\$/;/"
  done
  echo
  for f in "${FUNCS[@]}"; do
    body="$(extract "$f")"
    [[ -n "$body" ]] || { echo "extract_oracle: $f not found in $src" >&2; exit 1; }
    echo "$body" | sed "${sed_prog}"
    echo
  done
} > "$out"
echo "extract_oracle: wrote $out (${#FUNCS[@]} functions)"
