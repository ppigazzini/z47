#!/usr/bin/env python3
# Build the demonstration-program index from the *.p47u headers.
#
# Each *.p47u header gives these fields on '@' comment lines:
#     @ Index:   <3-8 word description>
#     @ Author:  <name(s)>          (optional)
#     @ Version: <version>          (optional)
# The first occurrence of each field is taken. The index lists one row
# per program: the file stem, the author, the version and the Index
# description, in aligned columns.
#
# Run from the Makefile 'index' target, or directly:
#     python3 mkindex.py

import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "Example-programs.txt")

FIELD = re.compile(r"^@\s*(Index|Author|Version)\s*:\s*(.*?)\s*$")


def sources():
  for name in sorted(os.listdir(HERE)):
    if name.endswith(".p47u"):
      yield name, os.path.join(HERE, name)
  for sub in sorted(os.listdir(HERE)):
    path = os.path.join(HERE, sub)
    if os.path.isdir(path):
      for name in sorted(os.listdir(path)):
        if name.endswith(".p47u"):
          yield sub + "/" + name, os.path.join(path, name)


def fields(path):
  got = {}
  with open(path, encoding="utf-8") as handle:
    for line in handle:
      match = FIELD.match(line)
      if match:
        key, value = match.group(1), match.group(2)
        got.setdefault(key, value)
  return got


def main():
  rows = []
  for rel, path in sources():
    got = fields(path)
    rows.append((rel[:-5], got.get("Author", ""), got.get("Version", ""), got.get("Index", "")))

  wProg = max(len(r[0]) for r in rows)
  wAuth = max(len(r[1]) for r in rows)
  wVer = max(len(r[2]) for r in rows)

  lines = []
  lines.append("Demonstration programs included in the C47/R47 distribution.")
  lines.append("Generated by 'make index' from the .p47u headers. Do not edit by hand.")
  lines.append("")
  head = "%-*s  %-*s  %-*s  %s" % (wProg, "Program", wAuth, "Author", wVer, "Ver", "Description")
  lines.append(head)
  lines.append("-" * len(head.rstrip()))
  for prog, auth, ver, desc in rows:
    lines.append(("%-*s  %-*s  %-*s  %s" % (wProg, prog, wAuth, auth, wVer, ver, desc)).rstrip())

  with open(OUT, "w", encoding="utf-8") as handle:
    handle.write("\n".join(lines) + "\n")


if __name__ == "__main__":
  main()
