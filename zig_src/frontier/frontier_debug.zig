// ---------------------------------------------------------------------------
// getDataTypeName
// ---------------------------------------------------------------------------
fn dataTypeNameKnown(dt: u32) bool {
    return switch (dt) {
        dtLongInteger, dtTime, dtDate, dtString, dtReal34Matrix, dtComplex34Matrix, dtShortInteger, dtReal34, dtComplex34, dtConfig => true,
        else => false,
    };
}

pub export fn getDataTypeName(dt: u16, article: bool_t, padWithBlanks: bool_t) [*c]const u8 {
    if (article and padWithBlanks) {
        if (dataTypeNameKnown(dt)) {
            return &typeName[3][dt + 1];
        } else {
            return &typeName[3][0];
        }
    } else if (article and !padWithBlanks) {
        if (dataTypeNameKnown(dt)) {
            return &typeName[2][dt + 1];
        } else {
            return &typeName[2][0];
        }
    } else if (!article and padWithBlanks) {
        if (dataTypeNameKnown(dt)) {
            return &typeName[1][dt + 1];
        } else {
            return &typeName[1][0];
        }
    } else if (!article and !padWithBlanks) {
        if (dataTypeNameKnown(dt)) {
            return &typeName[0][dt + 1];
        } else {
            return &typeName[0][0];
        }
    } else {
        return &typeName[0][0];
    }
}

