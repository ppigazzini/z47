// ---------------------------------------------------------------------------
// PC_BUILD-only stack-smashing detectors (host-only; the C symbols do not
// exist on firmware).
// ---------------------------------------------------------------------------
fn stackCheckImpl(begin: [*c]const u8, end: [*c]const u8, size: c_int, where: [*c]const u8) callconv(.c) void {
    var corrupted: c_int = 0;
    var i: c_int = 0;
    while (i < size) : (i += 1) {
        if (begin[@intCast(i)] != 0xaa) {
            _ = printf("Stack begin corrupted: begin[%d]=0x%02x at %s\n", i, @as(c_uint, begin[@intCast(i)]), where);
            corrupted = 1;
        }
    }
    i = 0;
    while (i < size) : (i += 1) {
        if (end[@intCast(i)] != 0xaa) {
            _ = printf("Stack end corrupted: end[%d]=0x%02x at %s\n", i, @as(c_uint, end[@intCast(i)]), where);
            corrupted = 1;
        }
    }
    if (corrupted != 0) {
        exit(0xBAD);
    }
}

fn initStackCheckImpl(begin: [*c]u8, end: [*c]u8, size: c_int) callconv(.c) void {
    _ = memset(begin, 0xaa, @intCast(size));
    _ = memset(end, 0xaa, @intCast(size));
}

fn stackSmashingTestImpl() callconv(.c) void {
    var stackEnd: [10000]u8 = undefined; // First declaration
    var v1: c_int = undefined;
    var v2: c_int = undefined;
    var v3: c_int = undefined;
    var stackBegin: [10000]u8 = undefined; // Last declaration

    initStackCheckImpl(&stackBegin, &stackEnd, 10000);

    v1 = 1;
    stackCheckImpl(&stackBegin, &stackEnd, 10000, "after v1 = ...");
    v2 = v1 + 1;
    stackCheckImpl(&stackBegin, &stackEnd, 10000, "after v2 = ...");
    v3 = v2 + 2;
    stackCheckImpl(&stackBegin, &stackEnd, 10000, "after v3 = ...");
    _ = printf("v1=%d v2=%d v3=%d\n", v1, v2, v3);
    stackCheckImpl(&stackBegin, &stackEnd, 10000, "after printf(...");
}

