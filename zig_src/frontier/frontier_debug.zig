// getRegisterTagName
// ---------------------------------------------------------------------------
var getRegisterTagName_base: [9]u8 = undefined;
pub export fn getRegisterTagName(regist: calcRegister_t, padWithBlanks: bool_t) [*c]const u8 {
    _ = padWithBlanks;
    switch (getRegisterDataType(regist)) {
        dtLongInteger => {
            switch (getRegisterTag(regist)) {
                LI_ZERO => return "zero    ",
                LI_NEGATIVE => return "negative",
                LI_POSITIVE => return "positive",
                else => return "???     ",
            }
        },
        dtReal34 => {
            switch (getRegisterTag(regist)) {
                amRadian => return "radian  ",
                amMultPi => return "multPi  ",
                amGrad => return "grad    ",
                amDegree => return "degree  ",
                amDMS => return "dms     ",
                amNone => return "none    ",
                else => return "???     ",
            }
        },
        dtComplex34 => {
            if (getComplexRegisterPolarMode(regist) != 0) {
                return "Polar   ";
            } else {
                return "Rect    ";
            }
        },
        dtString, dtReal34Matrix, dtComplex34Matrix, dtDate, dtTime, dtConfig => {
            switch (getRegisterTag(regist)) {
                amNone => return "        ",
                else => return "???     ",
            }
        },
        dtShortInteger => {
            abi.fmtBufZ(&getRegisterTagName_base, "base {d: >2} ", .{@as(u32, getRegisterTag(regist))});
            return &getRegisterTagName_base;
        },
        else => {
            return "???     ";
        },
    }
}

// ---------------------------------------------------------------------------
// LogBaseTwoOfPowersOfTwo
// ---------------------------------------------------------------------------
pub export fn LogBaseTwoOfPowersOfTwo(selection: u16) u16 {
    var jj: u16 = orOrtho(selection) & 0x03FF;
    jj = jj ^ (jj & (jj -% 1));
    var r: u16 = @intFromBool((jj & 0xAAAA) != 0);
    r |= @as(u16, @intFromBool((jj & 0xFF00) != 0)) << 3;
    r |= @as(u16, @intFromBool((jj & 0xF0F0) != 0)) << 2;
    r |= @as(u16, @intFromBool((jj & 0xCCCC) != 0)) << 1;
    return r;
}

