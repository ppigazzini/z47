// ---------------------------------------------------------------------------
// eatSpacesEnd (file-scope static tmp_names[20])
// ---------------------------------------------------------------------------
var eatSpacesEnd_tmp_names: [20]u8 = undefined;
pub export fn eatSpacesEnd(ss: [*c]const u8) [*c]u8 {
    _ = strcpy(&eatSpacesEnd_tmp_names, ss);
    var ix: i8 = @truncate(stringByteLength(ss) - 1);
    while (ix > 0) {
        if (ss[@intCast(ix)] == ' ') {
            eatSpacesEnd_tmp_names[@intCast(ix)] = 0;
        } else {
            break;
        }
        ix -= 1;
    }
    return &eatSpacesEnd_tmp_names;
}

// ---------------------------------------------------------------------------
// eatSpacesMid (file-scope static tmp_names[20])
// ---------------------------------------------------------------------------
var eatSpacesMid_tmp_names: [20]u8 = undefined;
pub export fn eatSpacesMid(ss: [*c]const u8) [*c]u8 {
    var tt: [50]u8 = undefined;
    var ix: i8 = 0;
    var iy: i8 = 0;

    _ = strcpy(&tt, ss);
    eatSpacesMid_tmp_names[0] = 0;
    while (tt[@intCast(ix)] != 0 and ix < 50) {
        if (tt[@intCast(ix)] != ' ') {
            eatSpacesMid_tmp_names[@intCast(iy)] = tt[@intCast(ix)];
            iy += 1;
        }
        ix += 1;
    }
    eatSpacesMid_tmp_names[@intCast(iy)] = 0;
    eatSpacesMid_tmp_names[@intCast(iy)] = 0;
    iy += 1;
    return &eatSpacesMid_tmp_names;
}

// ---------------------------------------------------------------------------
// getCurveFitModeNames. The PC_BUILD body builds errorMessage; on firmware the
// C returns the empty string.
// ---------------------------------------------------------------------------
pub export fn getCurveFitModeNames(selection: u16) [*c]const u8 {
    if (comptime !dmcp_build) {
        errorMessage[0] = 0;
        var ix: u16 = 0;
        while (ix < 10) : (ix += 1) {
            if ((selection & (@as(u16, 1) << @intCast(ix))) != 0) {
                _ = strcat(errorMessage, if (errorMessage[0] == 0) "" else " ");
                _ = strcat(errorMessage, eatSpacesEnd(getCurveFitModeName(@as(u16, 1) << @intCast(ix))));
            }
        }
        if (errorMessage[0] == 0) {
            return "???        ";
        }
        return errorMessage;
    } else {
        return "";
    }
}

